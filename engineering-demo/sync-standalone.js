/* Rebuild or verify the offline single-file edition from the shipped sources.
   node sync-standalone.js        # rewrite bridge-works-standalone.html
   node sync-standalone.js --check # fail if it is stale */
'use strict';
const fs = require('fs');
const path = require('path');
const here = __dirname;
const read = (name) => fs.readFileSync(path.join(here, name), 'utf8').replace(/\r\n/g, '\n');
const index = read('index.html');
const bundle = ['physics.js', 'levels.js', 'game.js'].map(read).join('\n\n');
/* NOTE: the replacement is a function so that `$` sequences inside the bundled
   sources (e.g. money() building '$' + value in game.js) are inserted literally
   instead of being interpreted as String.replace special patterns. */
const expected = index.replace(
  /<script src="physics\.js"><\/script>\s*<script src="levels\.js"><\/script>\s*<script src="game\.js"><\/script>/,
  () => '<!-- Single-file build: generated by sync-standalone.js; edit the source files. -->\n<script>\n' + bundle + '\n</script>'
);
const target = path.join(here, 'bridge-works-standalone.html');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || read('bridge-works-standalone.html') !== expected) {
    console.error('bridge-works-standalone.html is stale. Run: node sync-standalone.js');
    process.exit(1);
  }
  console.log('bridge-works-standalone.html is synchronized.');
} else {
  fs.writeFileSync(target, expected.replace(/\n/g, '\r\n'));
  console.log('Rebuilt bridge-works-standalone.html.');
}
